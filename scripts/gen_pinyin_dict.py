def main():
    out = {}
    for k, v in SYLLABLES.items():
        chars = []
        for c in v:
            if c not in chars:
                chars.append(c)
        out[k] = chars
    for k, v in PHRASES.items():
        words = [w.strip() for w in v.split(",") if w.strip()]
        existing = out.get(k, [])
        for w in words:
            if w not in existing:
                existing.append(w)
        out[k] = existing

    lines = []
    for k in sorted(out.keys(), key=lambda x: (len(x), x)):
        vals = ",".join(out[k][:40])
        lines.append("%s=%s" % (k, vals))

    path = r"d:\jqr_sheji01\HrDigitalHuman\app\src\main\assets\ime\pinyin_dict.txt"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
        f.write("\n")
    print("wrote", len(lines), "entries ->", path)


if __name__ == "__main__":
    main()
